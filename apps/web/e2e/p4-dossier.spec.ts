import { expect, test } from '@playwright/test';
import { PASSWORD, login, readyScenarioViaApi } from './helpers';

test('P4: model run, readiness gates, dossier freeze with PDF', async ({ page }) => {
  const s = await readyScenarioViaApi(page.request);
  await login(page, s.opEmail, PASSWORD);
  await page.goto(`/app/seasons/${s.seasonId}?tab=readiness`);
  await expect(page.getByTestId('gates')).toContainText('Modèle à jour');
  await expect(page.getByRole('link', { name: 'Corriger' })).toHaveCount(1); // only G7 (model) is missing

  // Model: save default seasonal assumptions (18 % flat, 6 months, bullet) and run
  await page.getByRole('tab', { name: 'Modèle' }).click();
  await page.getByRole('button', { name: 'Enregistrer les hypothèses' }).click();
  await expect(page.getByText('Modifications enregistrées.')).toBeVisible();
  await page.getByRole('button', { name: 'Calculer le modèle' }).click();
  await expect(page.getByTestId('model-current')).toHaveText('À jour');
  await expect(page.getByTestId('hcr-base')).toHaveText('1.45');
  await expect(page.getByTestId('hcr-combined')).toHaveText('1.05');

  // Readiness: all gates pass
  await page.getByRole('tab', { name: 'Préparation' }).click();
  await expect(page.getByRole('link', { name: 'Corriger' })).toHaveCount(0);
  const score = Number(await page.getByTestId('readiness-score').textContent());
  expect(score).toBeGreaterThan(40);

  // Dossier: freeze → PDF generated by the worker
  await page.getByRole('tab', { name: 'Dossier' }).click();
  await page.getByRole('button', { name: 'Figer le dossier' }).click();
  await expect(page.getByTestId('dossier-status-1')).toHaveText('Figé');
  await expect(page.getByTestId('dossier-pdf')).toBeVisible({ timeout: 30_000 });
  const signed = page.waitForResponse((r) => /\/v1\/dossiers\/[^/]+\/pdf$/.test(new URL(r.url()).pathname));
  await page.getByTestId('dossier-pdf').click();
  const { url } = (await (await signed).json()) as { url: string };
  const resp = await page.request.get(url);
  expect(resp.headers()['content-type']).toBe('application/pdf');
  expect((await resp.body()).subarray(0, 5).toString()).toBe('%PDF-');
  await page.goto(`/app/blocks/${s.blockId}`);
  await expect(page.getByTestId('block-status')).toHaveText('Prêt');
});
